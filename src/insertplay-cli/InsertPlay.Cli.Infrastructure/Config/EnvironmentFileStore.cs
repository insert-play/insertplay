using InsertPlay.Cli.Application.Abstractions;

namespace InsertPlay.Cli.Infrastructure.Config;

/// <summary>
/// Reads and writes the shell-sourceable ".env" file format used for runtime environment files.
/// Unifies what used to be a write-only helper in ConfigService and a read-only helper stuck in Program.cs.
/// </summary>
public sealed class EnvironmentFileStore(IFileSystem fileSystem) : IEnvironmentFileStore
{
    public void Write(string path, IReadOnlyDictionary<string, string> variables)
    {
        fileSystem.CreateDirectory(Path.GetDirectoryName(path)!);

        var lines = new List<string>
        {
            "# Auto-generated by InsertPlay CLI. Do not edit manually."
        };

        foreach (var pair in variables.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            if (!IsValidEnvKey(pair.Key))
                continue;

            var value = pair.Value.Replace("\r", " ").Replace("\n", " ");
            lines.Add($"export {pair.Key}={ShellQuote(value)}");
        }

        lines.Add(string.Empty);

        var tempPath = path + ".tmp";
        fileSystem.WriteAllLines(tempPath, lines);
        fileSystem.MoveFile(tempPath, path, overwrite: true);
    }

    public bool TryRead(string path, out Dictionary<string, string> variables, out string error)
    {
        variables = new Dictionary<string, string>(StringComparer.Ordinal);
        error = string.Empty;

        if (!fileSystem.FileExists(path))
        {
            error = $"Environment file not found: {path}";
            return false;
        }

        try
        {
            foreach (var rawLine in fileSystem.ReadAllLines(path))
            {
                var line = rawLine.Trim();
                if (string.IsNullOrWhiteSpace(line) || line.StartsWith('#'))
                    continue;

                if (line.StartsWith("export ", StringComparison.Ordinal))
                    line = line[7..].Trim();

                var separator = line.IndexOf('=');
                if (separator <= 0)
                    continue;

                var key = line[..separator].Trim();
                var value = line[(separator + 1)..].Trim();

                variables[key] = ParseEnvironmentValue(value);
            }

            return true;
        }
        catch (Exception ex)
        {
            error = $"Failed to read environment file '{path}': {ex.Message}";
            return false;
        }
    }

    private static string ParseEnvironmentValue(string value)
    {
        if (value.Length >= 2 && value[0] == '\'' && value[^1] == '\'')
        {
            var inner = value[1..^1];
            return inner.Replace("'\"'\"'", "'");
        }

        if (value.Length >= 2 && value[0] == '"' && value[^1] == '"')
        {
            var inner = value[1..^1];
            return inner.Replace("\\\"", "\"").Replace("\\\\", "\\");
        }

        return value;
    }

    private static bool IsValidEnvKey(string key)
    {
        if (string.IsNullOrWhiteSpace(key))
            return false;

        if (!(char.IsLetter(key[0]) || key[0] == '_'))
            return false;

        for (var i = 1; i < key.Length; i++)
        {
            var c = key[i];
            if (!(char.IsLetterOrDigit(c) || c == '_'))
                return false;
        }

        return true;
    }

    private static string ShellQuote(string value) => "'" + value.Replace("'", "'\"'\"'") + "'";
}
